    rows, used = [], set()
    for name, rx, page in CLUSTERS:
        r = re.compile(rx)
        ph = [p for p in hits if r.search(p) and p not in used]
        if not ph:
            continue
        used.update(ph)
        ph.sort(key=lambda p: (-len(seeds[p]), -hits[p], p))
        cs = set().union(*(seeds[p] for p in ph))
        rows.append((name, ph, page, len(cs), sum(hits[p] for p in ph)))
